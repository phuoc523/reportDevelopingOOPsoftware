import fs from 'node:fs/promises'
import path from 'node:path'
import { chromium } from 'playwright'

const out = path.resolve(process.env.ARTIFACT_DIR || 'artifacts/screenshots')
const kioskUrl = process.env.KIOSK_URL || 'http://127.0.0.1:7515'
const adminUrl = process.env.ADMIN_URL || 'http://127.0.0.1:7514'
const mockUrl = process.env.MOCK_PAYMENT_URL || 'http://127.0.0.1:3000'
const report = { startedAt: new Date().toISOString(), source: 'ScentStation React apps + local backend APIs + Playwright Chromium', realBankUsed: false, screenshots: [], checks: [], sprayStatus: 'NOT_ATTEMPTED' }

await fs.mkdir(out, { recursive: true })
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, deviceScaleFactor: 1 })

async function shot(page, name) {
  const file = path.join(out, name)
  await page.screenshot({ path: file, fullPage: true, animations: 'disabled' })
  report.screenshots.push(name)
}

async function login(page, username) {
  await page.getByLabel('Tên đăng nhập').fill(username)
  await page.getByLabel('Mật khẩu').fill('Demo@2026!')
  await page.getByRole('button', { name: 'Đăng nhập' }).click()
}

try {
  const admin = await context.newPage()
  await admin.goto(adminUrl, { waitUntil: 'networkidle' })
  await login(admin, 'brand.admin')
  await admin.getByRole('heading', { name: 'Tổng quan vận hành' }).waitFor({ timeout: 60000 })
  await admin.locator('.metric-grid').waitFor({ timeout: 60000 })
  await shot(admin, '06-admin-dashboard.png')
  report.checks.push({ name: 'Admin dashboard loaded from backend', result: 'OBSERVED' })

  await admin.getByRole('button', { name: /Kiosk$/ }).click()
  await admin.getByRole('heading', { name: 'Kiosk', exact: true }).waitFor()
  await admin.getByRole('cell', { name: 'Kiosk ScentStation Nguyễn Huệ' }).waitFor({ timeout: 60000 })
  await shot(admin, '07-admin-iot-machines.png')
  report.checks.push({ name: 'Admin machine records loaded', result: 'OBSERVED' })

  await admin.getByRole('button', { name: /Tồn kho$/ }).click()
  await admin.getByRole('heading', { name: 'Tồn kho', exact: true }).waitFor()
  await admin.locator('table tbody tr').first().waitFor({ timeout: 60000 })
  await admin.getByPlaceholder('Tìm trong dữ liệu đã tải…').fill('BOT-SS-91001')
  const bottle = admin.getByRole('row').filter({ hasText: 'BOT-SS-91001' })
  const currentQuantity = async () => {
    await bottle.waitFor()
    const headers = await admin.getByRole('columnheader').allTextContents()
    return Number((await bottle.getByRole('cell').nth(headers.indexOf('Còn lại (ml)')).innerText()).replace(',', '.'))
  }
  const inventoryBefore = await currentQuantity()
  report.inventoryBefore = inventoryBefore
  await shot(admin, '09-admin-inventory-before-spray.png')

  const kiosk = await context.newPage()
  await kiosk.goto(kioskUrl, { waitUntil: 'networkidle' })
  await login(kiosk, 'kiosk.customer')
  await kiosk.getByRole('heading', { name: 'Chọn mùi hương bạn muốn trải nghiệm' }).waitFor({ timeout: 60000 })
  await kiosk.locator('.product-card').first().waitFor({ timeout: 60000 })
  await shot(kiosk, '01-kiosk-fragrance-catalog.png')
  report.checks.push({ name: 'Kiosk catalog loaded from live service APIs', result: 'OBSERVED' })

  const tryButton = kiosk.locator('.product-card').filter({ hasText: 'SS-N01' }).getByRole('button', { name: 'Thử hương', exact: true })
  if (!(await tryButton.count()) || await tryButton.isDisabled()) {
    const note = await kiosk.locator('.warning-banner, .availability-note').first().innerText().catch(() => 'No available spray slot')
    report.checks.push({ name: 'Kiosk product selection', result: 'BLOCKED', detail: note })
    await shot(kiosk, '02-kiosk-product-unavailable.png')
    throw new Error(`No available product to select: ${note}`)
  }
  await tryButton.click()
  await kiosk.getByRole('heading', { name: 'Xác nhận lượt trải nghiệm' }).waitFor()
  await shot(kiosk, '02-kiosk-product-selected.png')
  report.checks.push({ name: 'Kiosk product selected', result: 'OBSERVED' })

  await kiosk.getByRole('button', { name: 'Thanh toán lượt thử' }).click()
  await kiosk.getByRole('heading', { name: 'Quét mã để thanh toán' }).waitFor({ timeout: 60000 })
  await kiosk.locator('.qr-wrap svg').waitFor()
  await shot(kiosk, '03-kiosk-mock-payment-qr.png')
  const reference = await kiosk.locator('.payment-details code').innerText()
  report.paymentReference = reference
  report.checks.push({ name: 'Payment QR generated by Order Service', result: 'OBSERVED' })

  const payment = await context.newPage()
  await payment.goto(`${mockUrl}/mock-payment/${encodeURIComponent(reference)}`, { waitUntil: 'networkidle' })
  await payment.getByRole('heading', { name: 'Thanh toán đơn hàng' }).waitFor({ timeout: 60000 })
  await payment.getByRole('button', { name: 'Xác nhận thanh toán' }).waitFor({ timeout: 60000 })
  await payment.getByRole('button', { name: 'Xác nhận thanh toán' }).click()
  await payment.getByText('Thanh toán thành công. Hệ thống đã xác nhận giao dịch và cập nhật đơn hàng.', { exact: true }).waitFor({ timeout: 60000 })
  await shot(payment, '04-kiosk-payment-confirmed-mock.png')
  report.checks.push({ name: 'Mock payment confirmed by local Order Service', result: 'OBSERVED' })

  const outcomePanel = kiosk.locator('.result-card, .dispensing-card')
  await outcomePanel.first().waitFor({ timeout: 60000 })
  await kiosk.locator('.result-card').waitFor({ timeout: 30000 }).catch(() => {})
  const dispenseText = await kiosk.locator('.result-card, .dispensing-card').first().innerText().catch(() => '')
  if (/DISPENSED|thử đã hoàn tất/i.test(dispenseText)) report.sprayStatus = 'DISPENSED'
  else if (/FAILED|lỗi/i.test(dispenseText)) report.sprayStatus = 'FAILED'
  else report.sprayStatus = 'PENDING_OR_UNKNOWN'
  await shot(kiosk, '05-kiosk-spray-status.png')
  report.kioskSprayStatusText = dispenseText

  for (let attempt = 0; attempt < 15; attempt++) {
    await admin.getByRole('button', { name: 'Làm mới' }).click()
    report.inventoryAfter = await currentQuantity()
    if (report.inventoryAfter !== inventoryBefore) break
    await new Promise(resolve => setTimeout(resolve, 2000))
  }
  await shot(admin, '10-admin-inventory-after-spray.png')
  report.inventoryChanged = report.inventoryBefore !== report.inventoryAfter
  report.checks.push({ name: 'Inventory viewed after actual dispense result', result: report.inventoryChanged ? 'CHANGED' : 'UNCHANGED' })

  await admin.getByRole('button', { name: /Đơn hàng & thanh toán/ }).click()
  await admin.getByRole('heading', { name: 'Đơn hàng & thanh toán', exact: true }).waitFor()
  await admin.getByPlaceholder('Tìm trong dữ liệu đã tải…').fill(reference)
  const paid = admin.getByRole('row').filter({ hasText: reference }).filter({ hasText: 'Đã thanh toán' })
  await paid.first().waitFor({ timeout: 60000 })
  await shot(admin, '08-admin-transactions.png')

  report.completedAt = new Date().toISOString()
  report.outcome = 'PAYMENT_CONFIRMED'
  if (report.sprayStatus !== 'DISPENSED' || Math.abs(inventoryBefore - report.inventoryAfter - 0.12) > 0.0001) {
    throw new Error(`Expected simulated dispense and a 0.12 ml decrement, observed ${report.sprayStatus}: ${inventoryBefore} → ${report.inventoryAfter}`)
  }
  report.outcome = 'PAYMENT_SIMULATED_SPRAY_AND_INVENTORY_CONFIRMED'
} catch (error) {
  report.completedAt = new Date().toISOString()
  report.outcome = 'INCOMPLETE'
  report.error = error instanceof Error ? error.message : String(error)
  for (const page of context.pages()) {
    const title = await page.title().catch(() => 'unknown')
    const name = title.toLowerCase().includes('admin') ? 'admin' : title.toLowerCase().includes('kiosk') ? 'kiosk' : 'page'
    await page.screenshot({ path: path.join(out, `failure-${name}.png`), fullPage: true }).catch(() => {})
  }
  throw error
} finally {
  await fs.writeFile(path.join(out, 'run-report.json'), `${JSON.stringify(report, null, 2)}\n`)
  await context.close()
  await browser.close()
}
